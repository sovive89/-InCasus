 check (phase in ('intake','investigation','prelitigation','judicial','execution','closed'));
alter table public.dossier_clients add constraint dossier_client_name_nonblank check(length(btrim(name)) > 0);
alter table public.dossier_cases add constraint dossier_case_fields_nonblank check(length(btrim(title)) > 0 and length(btrim(matter)) > 0);
alter table public.dossier_clients add constraint dossier_client_contact_bounds check(length(email) <= 254 and length(phone) <= 40);
alter table public.dossier_audit add column case_id uuid references public.dossier_cases;
create index dossier_cases_office_idx on public.dossier_cases(office_id,created_at desc);

-- Membership is provisioned only for an already verified professional account.
-- This does not promote a client or trust user-editable metadata.
create function private.dossier_start_office(office_name text) returns uuid
language plpgsql security definer set search_path='' as $$
declare actor uuid := auth.uid(); office uuid;
begin
 if actor is null or not public.has_legal_role(actor,'lawyer') then
  raise exception 'Acesso profissional necessário' using errcode='42501';
 end if;
 if office_name is null or length(btrim(office_name)) not between 1 and 180 then
  raise exception 'Informe o nome do escritório' using errcode='22023';
 end if;
 perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(actor::text,0));
 select m.office_id into office from public.dossier_members m
 join public.dossier_offices o on o.id=m.office_id
 where m.user_id=actor and m.role='owner' order by o.created_at,m.office_id limit 1;
 if office is not null then return office; end if;
 insert into public.dossier_offices(name) values(btrim(office_name)) returning id into office;
 insert into public.dossier_members(office_id,user_id,role) values(office,actor,'owner');
 insert into public.dossier_audit(office_id,actor_id,action) values(office,actor,'office.created');
 return office;
end $$;
revoke all on function private.dossier_start_office(text) from public,anon;
grant execute on function private.dossier_start_office(text) to authenticated;
create function public.dossier_start_office(office_name text) returns uuid
language sql security invoker set search_path='' as $$ select private.dossier_start_office(office_name); $$;
revoke all on function public.dossier_start_office(text) from public,anon;
grant execute on function public.dossier_start_office(text) to authenticated;

-- Column grants prevent account linking, membership changes and office reassignment.
grant insert(id,office_id,name,email,phone),update(name,email,phone) on public.dossier_clients to authenticated;
grant insert(id,office_id,client_id,title,matter,phase),update(title,matter,phase) on public.dossier_cases to authenticated;
create policy client_create on public.dossier_clients for insert to authenticated with check(private.dossier_staff(office_id));
create policy client_edit on public.dossier_clients for update to authenticated using(private.dossier_staff(office_id)) with check(private.dossier_staff(office_id));
create policy case_create on public.dossier_cases for insert to authenticated with check(private.dossier_staff(office_id));
create policy case_edit on public.dossier_cases for update to authenticated using(private.dossier_staff(office_id)) with check(private.dossier_staff(office_id));

-- Audit is generated by the database, in the same transaction as each write.
create function private.dossier_record_change() returns trigger
language plpgsql security definer set search_path='' as $$
declare client uuid; linked_case uuid;
begin
 if auth.uid() is null then raise exception 'Autor autenticado necessário' using errcode='42501'; end if;
 if tg_op='UPDATE' and new is not distinct from old then return new; end if;
 if tg_table_name='dossier_clients' then client := new.id;
 else client := new.client_id; linked_case := new.id; end if;
 insert into public.dossier_audit(office_id,actor_id,client_id,case_id,action)
 values(new.office_id,auth.uid(),client,linked_case,
  (case when tg_table_name='dossier_clients' then 'client.' else 'case.' end) || lower(tg_op));
 return new;
end $$;
revoke all on function private.dossier_record_change() from public,anon,authenticated;
create trigger dossier_client_audit after insert or update on public.dossier_clients for each row execute function private.dossier_record_change();
create trigger dossier_case_audit after insert or update on public.dossier_cases for each row execute function private.dossier_record_change();
